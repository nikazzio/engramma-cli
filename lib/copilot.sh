# shellcheck shell=bash

COPILOT_INSTRUCTIONS_MARKER='<!-- Generated by Engramma for Copilot CLI -->'

setup_copilot() {
	local rules content
	command -v copilot >/dev/null || return 0
	rules="$(shared_agent_rules)"
	content="$(
		echo "$COPILOT_INSTRUCTIONS_MARKER"
		if [[ -n "$rules" ]]; then
			cat -- "$rules" || exit 1
			printf '\n\n'
		fi
		print_managed_context_instructions
	)" || { problem "impossibile leggere le regole per Copilot"; return 1; }
	write_generated_instructions "$COPILOT_HOME_DIR/copilot-instructions.md" "$content" "istruzioni personali di Copilot" "$COPILOT_INSTRUCTIONS_MARKER"
	link_agent_skills "$COPILOT_HOME_DIR/skills" "Copilot"
}
