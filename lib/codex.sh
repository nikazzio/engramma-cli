# shellcheck shell=bash
# shellcheck disable=SC2153 # FILE, REF, CMD and the other colors come from lib/theme.sh

# Codex gets the same rules, skills and plugins as Claude Code, translated into
# the places it reads them from. Its config.toml holds machine data (trusted
# folders, hook approvals), so engramma only adds the keys it needs.

CODEX_HOME_DIR="${CODEX_HOME:-$HOME/.codex}"
CODEX_CONFIG="$CODEX_HOME_DIR/config.toml"
CODEX_SKILLS_DIR="$HOME/.agents/skills"
CODEX_INSTRUCTIONS_MARKER='<!-- Scritto da engramma'
# Codex stops reading instructions past this size (project_doc_max_bytes).
CODEX_MAX_BYTES=32768

uses_codex() {
	agent_enabled codex && command -v codex >/dev/null
}

setup_codex() {
	uses_codex || return 0
	write_codex_instructions
	link_codex_skills
	check_codex_shell_snapshot
	check_codex_fallback_filenames
	check_codex_code_graph
	check_codex_plugins
}

# Codex reads its global instructions as plain text, without following @file
# imports: engramma writes there the global rules of Claude Code followed by the
# instructions of boost, so both agents follow the same rules.
write_codex_instructions() {
	local rules content instructions="$CODEX_HOME_DIR/AGENTS.md"
	if $EXPLICIT_AGENTS; then
		rules="$(shared_agent_rules)"
	else
		# shellcheck disable=SC2016 # Match the literal legacy destination.
		rules="$(global_source_for '${CLAUDE_HOME}/CLAUDE.md')"
		[[ -n "$rules" ]] || return 0
	fi
	content="$(codex_instructions "$rules")" || { problem "impossibile leggere le regole per Codex"; return 1; }
	write_generated_instructions "$instructions" "$content" "AGENTS.md globale"
	check_codex_instructions_size "$instructions" "AGENTS.md globale"
}

# Writes a file generated by engramma, never one written by hand.
write_generated_instructions() {
	local file="$1" content="$2" label="$3" marker="${4:-}"

	if [[ -f "$file" && "$(cat "$file")" == "$content" ]]; then
		fine "${REF}$label${RESET} generato e allineato"
		return
	fi
	if [[ -e "$file" || -L "$file" ]]; then
		if ! owns_generated_instructions "$file" "$marker"; then
			problem "${REF}$label${RESET}: $(path "$file") scritto a mano, non lo sovrascrivo"
			fix_with 50 "confronta $(path "$file") con le regole dell’archivio prima di rilanciare"
			return
		fi
	fi

	case "$MODE" in
		dry) would "${REF}$label${RESET}: rigenererei $(path "$file")" ;;
		check) problem "${REF}$label${RESET} non allineato alle regole globali ${DIM}(eng setup lo rigenera)${RESET}" ;;
		*)
			if publish_generated_instructions "$file" "$content"; then
				ok "${REF}$label${RESET} rigenerato ${DIM}($(path "$file"))${RESET}"
			else
				problem "${REF}$label${RESET}: impossibile salvare $(path "$file")"
			fi
			;;
	esac
}

owns_generated_instructions() {
	local file="$1" marker="$2" first
	[[ -f "$file" ]] || return 1
	if [[ -z "$marker" ]]; then
		is_replaceable_codex_instructions "$file"
	else
		[[ ! -L "$file" ]] || return 1
		IFS= read -r first <"$file" || return 1
		[[ "$first" == "$marker" ]]
	fi
}

publish_generated_instructions() (
	local file="$1" content="$2" staging
	mkdir -p -- "$(dirname "$file")" || return 1
	staging="$(mktemp -- "$file.XXXXXXXX")" || return 1
	trap 'rm -f -- "$staging"' EXIT
	printf '%s\n' "$content" >"$staging" && mv -T -- "$staging" "$file"
)

# The file in global/ that links.txt sends to a destination, as written there.
global_source_for() {
	local source destination
	while read -r source destination _; do
		[[ "$destination" == "$1" && -f "$GLOBAL_DIR/$source" ]] && echo "$GLOBAL_DIR/$source" && return
	done < <(global_entries)
}

# Files written by engramma or by boost; anything else was written by hand.
is_replaceable_codex_instructions() {
	local file="$1" first
	first="$(grep -m 1 -vE '^[[:space:]]*$' "$file")"
	[[ "$first" == "$CODEX_INSTRUCTIONS_MARKER"* || "$first" == '<!-- Content of BOOST.md'* ]] && return 0
	[[ "$first" =~ ^@[^[:space:]]+$ && "$(grep -cvE '^[[:space:]]*$' "$file")" == 1 ]] && return 0
	cmp -s "$file" "$CODEX_HOME_DIR/BOOST.md"
}

codex_instructions() {
	local boost=false
	integration_enabled boost && [[ -f "$CODEX_HOME_DIR/BOOST.md" ]] && boost=true
	if $boost; then
		echo "$CODEX_INSTRUCTIONS_MARKER da $(tilde "$1") e $(tilde "$CODEX_HOME_DIR")/BOOST.md: non modificare qui, viene riscritto da eng sync. -->"
	else
		echo "$CODEX_INSTRUCTIONS_MARKER da $(tilde "$1"): non modificare qui, viene riscritto da eng sync. -->"
	fi
	echo
	if [[ -n "$1" ]]; then
		cat -- "$1" || return 1
		echo
	fi
	if $EXPLICIT_AGENTS; then
		print_managed_context_instructions
	else
		codex_repo_rule
	fi
	if $boost; then
		echo
		echo
		boost_without_manual_pipe "$CODEX_HOME_DIR/BOOST.md"
	fi
}

# Codex loads instructions only from the folder it was started in and its parents
# up to the repo root: started in a workspace folder it does not see those of the
# repos inside it, which Claude Code loads by itself.
codex_repo_rule() {
	cat <<'EOF'
# Istruzioni dei repo

Prima di lavorare in un repo dentro la cartella di avvio, leggi le sue istruzioni: `AGENTS.md` (o, se manca, `CLAUDE.md`) nella radice del repo e `CLAUDE.local.md`, se c'è. Una riga che inizia con `@` seguita da un percorso rimanda a un file: leggi anche quello. Vale anche per i repo in cui entri a metà sessione.
EOF
}

# The Rule section of boost asks to pipe every command by hand, but its hooks
# already rewrite them: that section is replaced, the rest is kept.
boost_without_manual_pipe() {
	awk '
		/^## Rule/ {
			print
			print ""
			print "Boost hooks are installed: eligible shell commands are rewritten automatically. Run commands normally; do not add `| boost` or any prefix by hand."
			print ""
			skip = 1
			next
		}
		skip && /^## / { skip = 0 }
		!skip
	' "$1"
}

# Codex reads skills in the same format as Claude Code, from ~/.agents/skills.
link_codex_skills() {
	link_agent_skills "$CODEX_SKILLS_DIR" "$(tilde "${CODEX_SKILLS_DIR%/skills}")"
}

# Codex keeps the environment of the folder it was started in, unless shell
# snapshots are off.
check_codex_shell_snapshot() {
	if grep -qsE '^[[:space:]]*shell_snapshot[[:space:]]*=[[:space:]]*false' "$CODEX_CONFIG"; then
		fine "features.shell_snapshot = false"
		return
	fi
	case "$MODE" in
		dry) would "codex features disable shell_snapshot" ;;
		check) problem "shell_snapshot attivo: Codex congela l'ambiente all'avvio e usa la stessa node ovunque" ;;
		*)
			if codex features disable shell_snapshot >/dev/null 2>&1 </dev/null; then
				ok "codex features disable shell_snapshot: ogni cartella usa la sua node"
			else
				problem "codex features disable shell_snapshot fallito"
				fix_with 50 "${CMD}codex features disable shell_snapshot${RESET}"
			fi
			;;
	esac
}

# Repos without AGENTS.md often have a CLAUDE.md of the team: with this key Codex
# reads it too, in the repo and in its subfolders.
check_codex_fallback_filenames() {
	local line
	line="$(grep -sE '^[[:space:]]*project_doc_fallback_filenames[[:space:]]*=' "$CODEX_CONFIG")"
	if [[ "$line" == *'"CLAUDE.md"'* || "$line" == *"'CLAUDE.md'"* ]]; then
		fine "project_doc_fallback_filenames include CLAUDE.md"
		return
	fi
	if [[ -n "$line" ]]; then
		problem "project_doc_fallback_filenames non include \"CLAUDE.md\": aggiungilo a mano ${DIM}($(path "$CODEX_CONFIG"))${RESET}"
		return
	fi
	case "$MODE" in
		dry) would "project_doc_fallback_filenames = [\"CLAUDE.md\"] in $(path "$CODEX_CONFIG")" ;;
		check) problem "project_doc_fallback_filenames assente: Codex ignora i CLAUDE.md dei repo senza AGENTS.md" ;;
		*)
			# A key outside any table must come before the first one.
			mkdir -p "$CODEX_HOME_DIR"
			touch "$CODEX_CONFIG"
			awk 'BEGIN { line = "project_doc_fallback_filenames = [\"CLAUDE.md\"]" }
				!done && /^[[:space:]]*\[/ { print line; print ""; done = 1 }
				{ print }
				END { if (!done) print line }' "$CODEX_CONFIG" >"$CODEX_CONFIG.engramma.$$" &&
				mv "$CODEX_CONFIG.engramma.$$" "$CODEX_CONFIG"
			ok "project_doc_fallback_filenames = [\"CLAUDE.md\"]: Codex legge i CLAUDE.md dei repo"
			;;
	esac
}

# code-review-graph answers Claude Code and Codex through an MCP server, which
# each agent registers in its own configuration.
check_codex_code_graph() {
	integration_enabled code-review-graph && command -v code-review-graph >/dev/null || return 0
	if grep -qs '^\[mcp_servers\.code-review-graph\]' "$CODEX_CONFIG"; then
		fine "MCP code-review-graph registrato in Codex"
	else
		problem "MCP code-review-graph non registrato in Codex"
		# shellcheck disable=SC2088 # shown to the user, who runs it in a shell
		fix_with 50 "${CMD}codex mcp add code-review-graph -- ~/.local/share/mise/shims/code-review-graph serve --auto-watch${RESET}"
	fi
}

CODEX_PLUGINS_FILE="$GLOBAL_DIR/codex/plugins.txt"

# The plugins and skills of Codex listed in global/codex/plugins.txt. A plugin
# from a marketplace is installed by engramma; the others come with their own
# installer, so engramma checks they are there and says how to install them.
check_codex_plugins() {
	# shellcheck disable=SC2034 # filled by ensure_codex_plugin through its name
	local kind name rest source state="" hint reported=" "
	[[ -f "$CODEX_PLUGINS_FILE" ]] || return 0
	grep -q '^[[:space:]]*plugin[[:space:]]' "$CODEX_PLUGINS_FILE" && state="$(codex_plugin_state)"

	while read -r kind name rest; do
		hint="$(sed -nE 's/^[^#]*#[[:space:]]*//p' <<<"$rest")"
		case "$kind" in
			plugin)
				source="${rest%%#*}"
				source="${source%"${source##*[![:space:]]}"}"
				ensure_codex_plugin "$name" "$source" "$state" reported
				;;
			skill)
				if [[ -d "$CODEX_SKILLS_DIR/$name" || -d "$CODEX_HOME_DIR/skills/$name" ]]; then
					fine "skill $name"
				else
					problem "skill $name assente in Codex"
					fix_with 52 "${CMD}$hint${RESET}"
				fi
				;;
			path)
				if [[ -e "${name/#\~/$HOME}" ]]; then
					fine "${REF}$name${RESET}"
				else
					problem "${REF}$name${RESET} non trovato: impossibile confermare l'installazione del componente Codex"
					fix_with 52 "${CMD}$hint${RESET}"
				fi
				;;
			*) problem "global/codex/plugins.txt: riga non valida \"$kind $name\" ${DIM}(tipi: plugin, skill, path)${RESET}" ;;
		esac
	done < <(read_list_file "$CODEX_PLUGINS_FILE")
}

ensure_codex_plugin() {
	local plugin="$1" source="$2" state="$3" marketplace="${1#*@}"
	local -n already_added="$4"
	if ! grep -qxF "marketplace $marketplace" <<<"$state" && [[ "$already_added" != *" $marketplace "* ]]; then
		already_added+="$marketplace "
		case "$MODE" in
			dry) would "codex plugin marketplace add $source" ;;
			check)
				problem "marketplace $marketplace non registrato in Codex ${DIM}(eng setup lo aggiunge)${RESET}"
				return
				;;
			*) codex_plugin_command "codex plugin marketplace add $source" plugin marketplace add "$source" || return ;;
		esac
	fi
	if grep -qxF "plugin $plugin" <<<"$state"; then
		fine "${REF}$plugin${RESET}"
		return
	fi
	case "$MODE" in
		dry) would "codex plugin add $plugin" ;;
		check) problem "${REF}$plugin${RESET} non installato in Codex ${DIM}(eng setup lo installa)${RESET}" ;;
		*) codex_plugin_command "codex plugin add $plugin" plugin add "$plugin" ;;
	esac
}

# One line per marketplace and per installed plugin of Codex.
codex_plugin_state() {
	{
		timeout 60 codex plugin marketplace list --json 2>/dev/null </dev/null
		echo
		timeout 60 codex plugin list --json 2>/dev/null </dev/null
	} | "$PYTHON" -c '
import json, sys
decoder, text, index = json.JSONDecoder(), sys.stdin.read(), 0
while index < len(text):
    if text[index].isspace():
        index += 1
        continue
    data, index = decoder.raw_decode(text, index)
    for item in data.get("marketplaces", []):
        print("marketplace", item.get("name"))
    for item in data.get("installed", []):
        if item.get("installed"):
            print("plugin", item.get("pluginId"))
' 2>/dev/null
}

codex_plugin_command() {
	local message="$1" output
	shift
	if output="$(GIT_SSH_COMMAND="ssh -o BatchMode=yes -o ConnectTimeout=10" timeout 180 codex "$@" 2>&1 </dev/null)"; then
		log_output "$output"
		ok "$message"
		return 0
	fi
	log_output "$output"
	problem "$message fallito ${DIM}($(grep -v '^WARNING' <<<"$output" | grep -v '^[[:space:]]*$' | tail -n 1))${RESET}"
	return 1
}

# Codex reads at most 32 KB of instructions from the folders it was started in:
# past that the rest is dropped without notice.
check_codex_instructions_size() {
	local file="$1" label="$2" size
	uses_codex && [[ -f "$file" ]] || return 0
	size="$(wc -c <"$file")"
	((size > CODEX_MAX_BYTES)) || return 0
	warn "${REF}$label${RESET}: $((size / 1024)) KB, oltre i 32 KB di project_doc_max_bytes ${DIM}(Codex tronca il resto senza avvisare · $(path "$file"))${RESET}"
}

# The file Codex reads at the root of a repo: the first it finds of these.
check_codex_repo_instructions() {
	local repo="$1" name="$2" file
	for file in AGENTS.override.md AGENTS.md CLAUDE.md; do
		if [[ -f "$repo/$file" ]]; then
			check_codex_instructions_size "$repo/$file" "$file"
			return 0
		fi
	done
}
